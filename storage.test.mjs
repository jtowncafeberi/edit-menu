import assert from 'node:assert/strict';
import {menuAPI} from './server/menu-api.js';
import {localDB} from './server/local-db.js';
import {MenuSync} from './menu-sync.js';
import {createEngine, SOURCE_ID} from './engine.js';
import data from './static/data.json' with {type:'json'};
const engine = createEngine(data,new Uint8Array(),new Uint8Array());
const price = data.fields.find(f=>f.page===2&&f.text==='69').id;
const name = data.fields.find(f=>f.page===2&&f.text==='Aloo Tikki Burger').id;
const DB=localDB(), env={DB};
const request = (path,init={})=>menuAPI(new Request('https://menu.test'+path,init),env);
const make = (edits={},stored,transport=request)=>new MenuSync({source:SOURCE_ID,edits,stored,validate:e=>engine.validate(e),onState:()=>{},request:transport});
let a=make();assert.equal(await a.connect(),true);assert.equal(a.revision,0);
await a.change({[price]:'149'});assert.equal(a.status,'saved');assert.equal(a.revision,1);
let b=make();await b.connect();assert.equal(b.edits[price],'149');
await b.change({...b.edits,[name]:'Aloo Burger'});assert.equal(b.revision,2);
await a.change({[price]:'159'});assert.equal(a.status,'conflict');
let fresh=make();await fresh.connect();assert.equal(fresh.edits[price],'149');assert.equal(fresh.edits[name],'Aloo Burger');
await a.connect({useSaved:true});assert.deepEqual(a.edits,fresh.edits);assert.equal(a.pending,false);
let online=false;
const network=(path,init)=>online?request(path,init):Promise.reject(Error('offline'));
let offline=make({...a.edits},a.metadata(),network);assert.equal(await offline.connect(),false);
await offline.change({...offline.edits,[price]:'169'});assert.equal(offline.pending,true);assert.equal(offline.status,'offline');
// Recreate a browser with its persisted edits + metadata, then resume saving.
offline=make(offline.edits,offline.metadata(),network);online=true;await offline.connect();await offline.flush();assert.equal(offline.status,'saved');assert.equal(offline.revision,3);
// A lost response is reconciled on reconnect without overwriting newer data.
let lose=true;
const lostResponse=async(path,init)=>{const r=await request(path,init);if(init?.method==='PUT'&&lose){lose=false;throw Error('connection lost');}return r;};
let lost=make({},undefined,lostResponse);await lost.connect();await lost.change({...lost.edits,[price]:'179'});assert.equal(lost.pending,true);await lost.connect();assert.equal(lost.pending,false);assert.equal(lost.revision,4);
let legacy=make({[price]:'99'});await legacy.connect();assert.equal(legacy.status,'conflict');assert.equal(legacy.edits[price],'99');
const put=(body,extra={})=>request('/api/menu',{method:'PUT',headers:{'Content-Type':'application/json',...extra},body:JSON.stringify(body)});
const body={source:SOURCE_ID,revision:4,mutationId:crypto.randomUUID(),edits:{[price]:'189'}};
let r=await put(body);assert.equal(r.status,200);assert.equal((await r.json()).revision,5);
r=await put(body);assert.equal(r.status,200,'Idempotent replay');assert.equal((await r.json()).revision,5);
assert.equal((await put({...body,mutationId:crypto.randomUUID()})).status,409);
assert.equal((await put({...body,revision:5,edits:{unknown:'1'}})).status,422);
assert.equal((await put({...body,revision:5,edits:{[price]:'bad'}})).status,422);
assert.equal((await put({...body,source:'another-menu'})).status,422);
assert.equal((await put(body,{Origin:'https://other.test'})).status,403);
assert.equal((await request('/api/menu',{method:'POST'})).status,405);
assert.equal((await request('/api/menu',{method:'PUT',headers:{'Content-Type':'application/json'},body:' '.repeat(131073)})).status,413);
assert.equal((await menuAPI(new Request('https://menu.test/api/menu'),{})).status,503);
assert.equal((await request('/api/menu')).headers.get('cache-control'),'no-store');
await lost.connect({useSaved:true});await lost.change({});fresh=make();await fresh.connect();assert.deepEqual(fresh.edits,{});assert.ok(fresh.updatedAt);
DB.close();console.log('Shared storage: restore, CAS conflicts, offline resume, lost responses, migration, validation, limits, reset and timestamps passed.');
